"""One test per file in tests/scenarios/; contract scenarios report as skipped (pending)."""

import unittest

from django.core.management import call_command
from django.test import TestCase, TransactionTestCase

import cya.testing.bindings  # noqa: F401 - registers step bindings
from cya.testing.scenarios import load_scenarios, run_scenario


class ScenarioMixin:
    def __init__(self, methodName="test_scenario", scenario=None):
        super().__init__(methodName)
        self.scenario = scenario

    def id(self):
        name = self.scenario.scenario_id if self.scenario else "unloaded"
        return f"{__name__}.{name}"

    def __str__(self):
        return self.id()

    # unittest compares tests by type and method name only, and Django's runner
    # drops "duplicate" tests, so include the scenario in equality and hashing.
    def __eq__(self, other):
        return isinstance(other, ScenarioMixin) and self.id() == other.id()

    def __hash__(self):
        return hash((ScenarioMixin, self.id()))

    def test_scenario(self):
        if self.scenario is None:
            self.skipTest("scenario tests are generated by this module's load_tests")
        run_scenario(self.scenario)


class ScenarioTest(ScenarioMixin, TestCase):  # bound steps use the test database
    pass


class CommittingScenarioTest(ScenarioMixin, TransactionTestCase):
    """For scenarios with "database": "commit": audited commands need real commits."""

    def tearDown(self):
        # Django's own teardown flush uses DELETE, which append-only tables reject.
        # Truncating first (reset_sequences) leaves nothing for it to delete, as the
        # other committing tests do.
        call_command("flush", verbosity=0, interactive=False, reset_sequences=True)
        super().tearDown()


def load_tests(loader, standard_tests, pattern):
    suite = unittest.TestSuite()
    for scenario in load_scenarios():
        case = CommittingScenarioTest if scenario.commits else ScenarioTest
        suite.addTest(case(scenario=scenario))
    return suite
